def _resolve_circuit(event_name: Optional[str], location: Optional[str]) -> Dict[str, Any]:
    event_key = _normalise_key(event_name)
    if event_key and event_key in _EVENT_COORDINATES:
        return _EVENT_COORDINATES[event_key]

    location_key = _normalise_key(location)
    if location_key and location_key in _LOCATION_COORDINATES:
        return _LOCATION_COORDINATES[location_key]

    raise KeyError(
        f"Unable to resolve coordinates for event={event_name!r}, location={location!r}"
    )


def _wind_direction_to_cardinal(degrees: Optional[float]) -> Optional[str]:
    if degrees is None:
        return None
    bearings = ["N", "NE", "E", "SE", "S", "SW", "W", "NW"]
    idx = int((float(degrees) % 360) / 45 + 0.5) % len(bearings)
    return bearings[idx]


def _extract_hourly_block(hourly: Dict[str, List[Any]], target_date: date) -> List[Dict[str, Any]]:
    times = hourly.get("time") or []
    if not times:
        return []

    results: List[Dict[str, Any]] = []
    fields = {
        "temperature_2m": hourly.get("temperature_2m") or [],
        "precipitation": hourly.get("precipitation") or [],
        "precipitation_probability": hourly.get("precipitation_probability"),
        "cloudcover": hourly.get("cloudcover") or [],
        "windspeed_10m": hourly.get("windspeed_10m") or [],
        "winddirection_10m": hourly.get("winddirection_10m") or [],
    }

    for index, time_str in enumerate(times):
        try:
            dt = datetime.fromisoformat(time_str)
        except ValueError:
            continue
        if dt.date() != target_date:
            continue

        entry: Dict[str, Any] = {"time": time_str}
        entry["temperature_2m"] = _safe_index(fields["temperature_2m"], index)
        entry["precipitation"] = _safe_index(fields["precipitation"], index)
        if fields["precipitation_probability"] is not None:
            entry["precipitation_probability"] = _safe_index(
                fields["precipitation_probability"], index
            )
        entry["cloudcover"] = _safe_index(fields["cloudcover"], index)
        entry["windspeed_10m"] = _safe_index(fields["windspeed_10m"], index)
        wind_dir = _safe_index(fields["winddirection_10m"], index)
        entry["winddirection_10m"] = wind_dir
        entry["winddirection_cardinal"] = (
            _wind_direction_to_cardinal(wind_dir) if wind_dir is not None else None
        )
        results.append(entry)

    return results


def _safe_index(sequence: Iterable[Any], index: int) -> Optional[Any]:
    if isinstance(sequence, list):
        if 0 <= index < len(sequence):
            return sequence[index]
        return None
    try:
        seq_list = list(sequence)
        if 0 <= index < len(seq_list):
            return seq_list[index]
    except TypeError:
        pass
    return None


def _build_daily_entry(
    label: str,
    target_date: date,
    daily: Dict[str, List[Any]],
    hourly: Dict[str, List[Any]],
    daily_units: Dict[str, Any],
) -> Dict[str, Any]:
    summary: Dict[str, Any] = {}
    day_str = target_date.isoformat()
    times = daily.get("time") or []
    idx = next((i for i, value in enumerate(times) if value == day_str), None)

    if idx is not None:
        summary["temperature_max"] = _safe_index(daily.get("temperature_2m_max") or [], idx)
        summary["temperature_min"] = _safe_index(daily.get("temperature_2m_min") or [], idx)
        summary["precipitation_sum"] = _safe_index(daily.get("precipitation_sum") or [], idx)
        summary["cloudcover_mean"] = _safe_index(daily.get("cloudcover_mean") or [], idx)
        summary["windspeed_max"] = _safe_index(daily.get("windspeed_10m_max") or [], idx)
        wind_dom = _safe_index(daily.get("winddirection_10m_dominant") or [], idx)
        summary["winddirection_dominant"] = wind_dom
        summary["winddirection_cardinal"] = (
            _wind_direction_to_cardinal(wind_dom) if wind_dom is not None else None
        )
    else:
        summary = {
            "temperature_max": None,
            "temperature_min": None,
            "precipitation_sum": None,
            "cloudcover_mean": None,
            "windspeed_max": None,
            "winddirection_dominant": None,
            "winddirection_cardinal": None,
        }

    return {
        "date": day_str,
        "label": label,
        "summary": summary,
        "hourly": _extract_hourly_block(hourly, target_date),
        "units": {
            "temperature_max": daily_units.get("temperature_2m_max"),
            "temperature_min": daily_units.get("temperature_2m_min"),
            "precipitation_sum": daily_units.get("precipitation_sum"),
            "cloudcover_mean": daily_units.get("cloudcover_mean"),
            "windspeed_max": daily_units.get("windspeed_10m_max"),
            "winddirection_dominant": daily_units.get("winddirection_10m_dominant"),
        },
    }


def _select_target_event(
    calendar_payload: Dict[str, Any],
    year: int,
    event_name: Optional[str],
) -> Dict[str, Any]:
    data = calendar_payload.get("data", {})
    events = data.get(str(year))
    if not events:
        raise ValueError(f"No calendar data available for year={year}")

    if event_name:
        needle = _normalise_key(event_name)
        for item in events:
            # Try exact match on event_name first
            if _normalise_key(item.get("event_name")) == needle:
                return item
            # Try partial match on event_name (e.g., "Mexico" matches "Mexico City Grand Prix")
            if needle in _normalise_key(item.get("event_name")):
                return item
            # Try match on country
            if _normalise_key(item.get("country")) == needle:
                return item
            # Try match on location
            if _normalise_key(item.get("location")) == needle:
                return item
        raise ValueError(f"Event {event_name!r} not found in calendar for year={year}")

    upcoming = [
        item for item in events if isinstance(item.get("days_until_race"), (int, float))
    ]
    upcoming = [item for item in upcoming if (item.get("days_until_race") or 0) >= 0]

    if upcoming:
        return min(upcoming, key=lambda item: item.get("days_until_race", 0))

    # Season finished – pick the most recent by race_date_utc
    def _parse_date(value: Optional[str]) -> datetime:
        if not value:
            return datetime.min.replace(tzinfo=timezone.utc)
        try:
            return datetime.fromisoformat(value)
        except ValueError:
            return datetime.min.replace(tzinfo=timezone.utc)

    return max(events, key=lambda item: _parse_date(item.get("race_date_utc")))


def _load_calendar_data(
    *,
    force_refresh: bool,
    calendar_data: Optional[Dict[str, Any]] = None,
) -> Tuple[Dict[str, Any], Optional[str], Dict[str, Any]]:
    if calendar_data is not None:
        return calendar_data, None, {"source": "injected"}

    freshness = check_calendar_freshness(all_years=True)

    needs_regen = (
        not freshness.get("exists")
        or freshness.get("should_regenerate", False)
        or force_refresh
    )

    if needs_regen:
        print("\n[INFO] Generating latest season calendar data for weather lookup...")
        generate_season_calendar(save_json=True, all_years=True, force=True)
        freshness = check_calendar_freshness(all_years=True)

    calendar_path = freshness.get("path")
    if not calendar_path:
        raise FileNotFoundError("Unable to locate season calendar JSON for weather analysis")

    with open(calendar_path, "r", encoding="utf-8") as handle:
        payload = json.load(handle)

    return payload, calendar_path, freshness


