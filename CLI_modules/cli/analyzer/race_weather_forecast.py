def check_weather_forecast_freshness(
    year: Optional[int] = None,
    event_name: Optional[str] = None,
) -> Dict[str, Any]:
    """
    Inspect the JSON/weather directory for the latest race weather file.
    """
    if not WEATHER_OUTPUT_DIR.exists():
        return {
            "exists": False,
            "path": None,
            "age_hours": None,
            "age_formatted": None,
            "is_fresh": False,
            "should_regenerate": True,
            "refresh_interval_hours": WEATHER_REFRESH_HOURS,
            "reason": "weather output directory does not exist",
        }

    pattern = "race_weather_forecast_*.json"
    event_slug = None
    if event_name:
        event_slug = _slugify(event_name)
    if year is not None and event_slug:
        pattern = f"race_weather_forecast_{year}_{event_slug}_*.json"
    elif year is not None:
        pattern = f"race_weather_forecast_{year}_*.json"
    elif event_slug:
        pattern = f"race_weather_forecast_*_{event_slug}_*.json"

    candidates = sorted(
        WEATHER_OUTPUT_DIR.glob(pattern),
        key=lambda path: path.stat().st_mtime,
        reverse=True,
    )

    if not candidates:
        return {
            "exists": False,
            "path": None,
            "age_hours": None,
            "age_formatted": None,
            "is_fresh": False,
            "should_regenerate": True,
            "refresh_interval_hours": WEATHER_REFRESH_HOURS,
            "reason": f"no files match pattern {pattern}",
        }

    latest = candidates[0]
    file_time = datetime.fromtimestamp(latest.stat().st_mtime, tz=timezone.utc)
    now = datetime.now(timezone.utc)
    age = now - file_time
    age_hours = age.total_seconds() / 3600
    is_fresh = age_hours < WEATHER_REFRESH_HOURS

    return {
        "exists": True,
        "path": str(latest),
        "file_time": file_time.isoformat(),
        "current_time": now.isoformat(),
        "age_hours": round(age_hours, 2),
        "age_formatted": _format_timedelta(age),
        "is_fresh": is_fresh,
        "should_regenerate": not is_fresh,
        "refresh_interval_hours": WEATHER_REFRESH_HOURS,
        "reason": "fresh file available" if is_fresh else "file older than refresh interval",
    }


def _format_timedelta(delta: timedelta) -> str:
    total_seconds = int(delta.total_seconds())
    if total_seconds < 60:
        return f"{total_seconds} seconds"
    minutes = total_seconds // 60
    if minutes < 60:
        return f"{minutes} minutes"
    hours = minutes // 60
    if hours < 24:
        return f"{hours} hours {minutes % 60} minutes"
    days = hours // 24
    return f"{days} days {hours % 24} hours"


