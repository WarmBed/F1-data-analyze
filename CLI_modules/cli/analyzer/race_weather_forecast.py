def _normalise_key(value: Optional[str]) -> str:
    if not value:
        return ""
    normalised = unicodedata.normalize("NFKD", value)
    ascii_only = "".join(ch for ch in normalised if ch.isascii())
    return ascii_only.strip().lower()


def _slugify(value: str) -> str:
    """
    Convert a race/event name into a filesystem-friendly token.
    """
    normalised = unicodedata.normalize("NFKD", value)
    ascii_only = "".join(ch for ch in normalised if ch.isascii())
    filtered = "".join(ch if ch.isalnum() else "_" for ch in ascii_only.strip().lower())
    while "__" in filtered:
        filtered = filtered.replace("__", "_")
    return filtered.strip("_") or "unknown"


